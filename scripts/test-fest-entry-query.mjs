import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const compile = source => ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, verbatimModuleSyntax: true } }).outputText;
const moduleUrl = source => `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`;
const model = moduleUrl(compile(await readFile(new URL('../src/lib/fest/model.ts', import.meta.url), 'utf8')));
const source = compile(await readFile(new URL('../src/components/fest/entryQuery.ts', import.meta.url), 'utf8')).replace("from '@/lib/fest/model'", `from '${model}'`);
const { entryTokenFromQuery, createEntryReader } = await import(moduleUrl(source));
let tests = 0;
function test(name, check) { check(); tests++; console.log(`✓ ${name}`); }
const token = 'abcdef0123456789abcdef0123456789';
test('Acepta un único token opaco de 32 caracteres', () => assert.equal(entryTokenFromQuery(`?panel=fest&entrada=${token}`), token));
test('Normaliza las mayúsculas sin cambiar la identidad de la entrada', () => assert.equal(entryTokenFromQuery(`?entrada=${token.toUpperCase()}`), token));
test('Los parámetros de acción no forman parte del resultado', () => assert.equal(entryTokenFromQuery(`?entrada=${token}&accion=checkin&cancelar=true`), token));
for (const query of ['', '?entrada=', '?entrada=abc', `?entrada=${token}0`, `?entrada=${token}&entrada=${token}`, '?entrada=javascript:alert(1)', `?entrada=https://example.invalid/verify/${token}`, `?entrada=MF-${token}`, `?entrada=%20${token}`, `?entrada=${token}%0A`, `?Entrada=${token}`]) test(`Ignora una query insegura o ambigua ${JSON.stringify(query)}`, () => assert.equal(entryTokenFromQuery(query), ''));
let calls = 0;
const read = createEntryReader(async value => { calls++; return { eventId: 'qa-event', code: `MF-${value}` }; });
const first = read(`qa-user:${token}:0`, token);
const replay = read(`qa-user:${token}:0`, token);
test('La repetición del efecto comparte la misma promesa de lectura', () => assert.equal(first, replay));
await Promise.all([first, replay]);
test('Repetir el efecto solo realiza una lectura', () => assert.equal(calls, 1));
await read(`qa-user:${token}:1`, token);
test('Un reintento explícito permite volver a leer', () => assert.equal(calls, 2));
await read(`qa-other-user:${token}:0`, token);
test('Otra identidad no reutiliza una lectura anterior', () => assert.equal(calls, 3));
let failures = 0;
const rejected = createEntryReader(async () => { failures++; throw new Error('Lectura de prueba interrumpida'); });
await Promise.allSettled([rejected('key:0', token), rejected('key:0', token)]);
test('Un error tampoco crea un bucle de lecturas', () => assert.equal(failures, 1));
await Promise.allSettled([rejected('key:1', token)]);
test('Tras un error solo un reintento explícito genera otra lectura', () => assert.equal(failures, 2));
console.log(`\n${tests} comprobaciones de entrada por QR correctas. Solo lectura; sin red ni mutaciones.`);

import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';

const source = await readFile(new URL('../src/lib/moonContent.ts', import.meta.url), 'utf8');
const websiteSource = await readFile('C:/MOON STUDIOS PAGINA WEB/src/lib/moonContent.ts', 'utf8');
assert.equal(source, websiteSource, 'Dashboard and website must use the same contract');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { DEFAULT_MOON_CONTENT, normalizeMoonContent, validateMoonContent, safeUrl } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);

assert.deepEqual(normalizeMoonContent(undefined), normalizeMoonContent(DEFAULT_MOON_CONTENT));
const blank = normalizeMoonContent({ hero: { description: '' }, faq: { items: [] }, socials: [], about: { stats: [] } });
assert.equal(blank.hero.description, '');
assert.deepEqual(blank.faq.items, []);
assert.deepEqual(blank.socials, []);
assert.deepEqual(blank.about.stats, []);
assert.equal(blank.hero.title, DEFAULT_MOON_CONTENT.hero.title);
assert.equal(validateMoonContent(DEFAULT_MOON_CONTENT).length, 0);
assert.ok(validateMoonContent({ ...DEFAULT_MOON_CONTENT, sections: DEFAULT_MOON_CONTENT.sections.map(s => ({ ...s, visible: false })) }).length);
for (const url of ['javascript:alert(1)', 'data:text/html,bad', '//evil.example', 'https://user:password@example.com', '/\\evil.example', 'https://exa\nmple.com']) assert.equal(safeUrl(url), '', url);
assert.equal(safeUrl('/cotizar'), '/cotizar');
assert.equal(safeUrl('#contacto'), '#contacto');
assert.equal(safeUrl('mailto:hello@example.com', '', { contact: true }), 'mailto:hello@example.com');
assert.equal(safeUrl('tel:+51916053628', '', { contact: true }), 'tel:+51916053628');
assert.equal(safeUrl(''), '');
const legacyLogo = 'https://ufvebjscabomuayqtyyo.supabase.co/storage/v1/object/public/ANDRE/moonstudios_logotipo_500x500_negro.png';
const rebrand = normalizeMoonContent({ brand: { logo: legacyLogo, ogImage: legacyLogo } });
assert.equal(rebrand.brand.logo, DEFAULT_MOON_CONTENT.brand.logo);
assert.equal(rebrand.brand.ogImage, DEFAULT_MOON_CONTENT.brand.ogImage);
assert.equal(normalizeMoonContent({ brand: { logo: '' } }).brand.logo, '');
assert.equal(normalizeMoonContent({ brand: { logo: 'https://example.com/custom.png' } }).brand.logo, 'https://example.com/custom.png');
const hostile = normalizeMoonContent({ brand: { logo: 'javascript:alert(1)' }, socials: [{ id: 'bad', label: 'Bad', url: 'data:text/html,bad' }], footer: { products: [{ id: 'bad', label: 'Bad', url: 'javascript:alert(1)' }] } });
assert.equal(hostile.brand.logo, '');
assert.equal(hostile.socials[0].url, '');
assert.equal(hostile.footer.products[0].url, '');
const sections = normalizeMoonContent({ sections: [{ id: 'faq', label: 'FAQ', visible: false }, { id: 'faq', label: 'Duplicate', visible: true }, { id: 'invalid', label: '', visible: true }] });
assert.equal(sections.sections.length, 9);
assert.equal(sections.sections[0].id, 'faq');
assert.equal(sections.sections[0].visible, false);
assert.equal(new Set(sections.sections.map(s => s.id)).size, 9);
const malformed = normalizeMoonContent({ brand: null, hero: { disciplines: [null, {}, 'Web'] }, faq: { items: [null, 12, { question: 'Q', answer: 'A' }] } });
assert.deepEqual(malformed.hero.disciplines, ['Web']);
assert.equal(malformed.faq.items.length, 1);
assert.equal(malformed.faq.items[0].question, 'Q');
const collision = normalizeMoonContent({ faq: { items: ['a', 'a-2', 'a', 'a-1', 'a', 'a-1-1'].map(id => ({ id, question: id, answer: 'A' })) } });
assert.equal(new Set(collision.faq.items.map(item => item.id)).size, collision.faq.items.length, 'Duplicate repair must avoid existing suffixed IDs');
assert.deepEqual(normalizeMoonContent(collision), collision, 'Repaired IDs must remain stable on another import');
assert.deepEqual(normalizeMoonContent({ faq: { items: ['a', 'a-2', 'a', 'a-1', 'a', 'a-1-1'].map(id => ({ id, question: id, answer: 'A' })) } }), collision, 'Duplicate repair must be deterministic');
console.log('CMS contract verified: shared schema, defaults, intentional blanks, malicious URLs, malformed imports and section ordering.');

import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';

const source = await readFile(new URL('../src/lib/sessionIdentity.ts', import.meta.url), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { TabSessionKeys, sessionStorageKeyFor, createSessionRemovalGuard } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const values = new Map([['sessionKey', 'legacy-user-a-key']]);
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
let serial = 0;
const keys = new TabSessionKeys(() => storage, () => `synthetic-${++serial}`);
let checks = 0;
const check = run => { run(); checks++; };
check(() => assert.equal(keys.read('user-a'), null));
check(() => assert.equal(keys.ensure('user-a'), 'synthetic-1'));
check(() => assert.equal(keys.ensure('user-a'), 'synthetic-1'));
check(() => assert.equal(keys.ensure('user-b'), 'synthetic-2'));
check(() => assert.equal(keys.read('user-a'), 'synthetic-1'));
check(() => assert.equal(keys.read('user-b'), 'synthetic-2'));
check(() => assert.equal(values.get('sessionKey'), 'legacy-user-a-key'));
check(() => assert.equal(values.get(sessionStorageKeyFor('user-a')), 'synthetic-1'));
check(() => assert.equal(values.get(sessionStorageKeyFor('user-b')), 'synthetic-2'));
check(() => assert.equal(sessionStorageKeyFor('user/a:b'), 'moon-session:user%2Fa%3Ab'));
check(() => assert.notEqual(sessionStorageKeyFor('user/a'), sessionStorageKeyFor('user%2Fa')));
const reloaded = new TabSessionKeys(() => storage, () => { throw new Error('A persisted key must not be replaced.'); });
check(() => assert.equal(reloaded.ensure('user-a'), 'synthetic-1'));
check(() => assert.equal(reloaded.ensure('user-b'), 'synthetic-2'));
const blocked = new TabSessionKeys(() => { throw new Error('Storage denied'); }, () => `memory-${++serial}`);
check(() => assert.equal(blocked.ensure('user-a'), 'memory-3'));
check(() => assert.equal(blocked.ensure('user-a'), 'memory-3'));
check(() => assert.equal(blocked.ensure('user-b'), 'memory-4'));
check(() => assert.equal(blocked.read('user-a'), 'memory-3'));
check(() => assert.throws(() => keys.ensure(''), /cuenta/));
check(() => assert.throws(() => keys.read(''), /cuenta/));
let currentUid = 'user-a';
let removals = 0;
const receive = createSessionRemovalGuard('user-a', () => currentUid, () => { removals++; });
const server = { fromCache: false, hasPendingWrites: false };
receive({ ...server, exists: false });
check(() => assert.equal(removals, 0));
receive({ ...server, exists: true });
receive({ exists: false, fromCache: true, hasPendingWrites: false });
check(() => assert.equal(removals, 0));
receive({ exists: false, fromCache: false, hasPendingWrites: true });
check(() => assert.equal(removals, 0));
currentUid = 'user-b';
receive({ ...server, exists: false });
check(() => assert.equal(removals, 0));
currentUid = null;
receive({ ...server, exists: false });
check(() => assert.equal(removals, 0));
currentUid = 'user-a';
receive({ ...server, exists: false });
check(() => assert.equal(removals, 1));
receive({ ...server, exists: false });
receive({ ...server, exists: true });
receive({ ...server, exists: false });
check(() => assert.equal(removals, 1));
let confirmedRemovals = 0;
const confirmed = createSessionRemovalGuard('user-a', () => currentUid, () => { confirmedRemovals++; }, true);
confirmed({ exists: false, fromCache: true, hasPendingWrites: false });
check(() => assert.equal(confirmedRemovals, 0));
confirmed({ ...server, exists: false });
check(() => assert.equal(confirmedRemovals, 1));
console.log(`Session identity: ${checks} checks passed (account isolation, tab reload, legacy key rejection, denied storage and confirmed server-only removal).`);
